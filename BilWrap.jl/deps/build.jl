# deps/build.jl

const package_root = joinpath(@__DIR__, "..")

# 1. Match your CMake directory structure
# As per CMakeLists: set(BIL_LIBDIR ${BIL_PATH}/lib)
const P_dir = "/usr/local/lib"

# 2. Extract the raw version tag directly from the VERSION file
const version_file = joinpath(package_root, "BIL_VERSION")
const bil_version = if isfile(version_file)
    strip(read(version_file, String)) # Reads the exact version string
else
    error("VERSION file missing from package root: $version_file")
end

# 3. Extract the build type tag directly from the BUILDTYPE file
const buildtype_file = joinpath(package_root, "BIL_BUILDTYPE")
const bil_buildtype = if isfile(buildtype_file)
    strip(read(buildtype_file, String)) # Reads the exact buildtype string
else
const bil_buildtype = "Release"
end

# 4. Handle cross-platform shared library extensions automatically
const lib_ext = if Sys.iswindows()
    ".dll"
elseif Sys.isapple()
    ".dylib"
else
    ".so" # Linux / Unix
end

# 5. Mirror CMake's exact naming pattern: bil-${BIL_VERSION}-${CMAKE_BUILD_TYPE}
# Windows prefix rules apply if compiling directly for native Win32/MinGW
const lib_prefix = Sys.iswindows() ? "" : "lib"

@show lib_prefix
@show bil_version
@show bil_buildtype
@show lib_ext

const L_name = "$(lib_prefix)bil-$(bil_version)-$(bil_buildtype)_julia$(lib_ext)"
const full_library_path = joinpath(P_dir, L_name)

# 6. Write out the static configuration file for Julia's caching system
const output_config_file = joinpath(@__DIR__, "deps_vars.jl")

open(output_config_file, "w") do f
    println(f, "# Auto-generated by deps/build.jl. DO NOT EDIT.")
    println(f, "const CPP_SHARED_LIB_PATH = ", repr(full_library_path))
end

@info "MyPackage configured for C++ binary: $L_name"

